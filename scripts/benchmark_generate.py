"""Compare two-pass generation time and generated source size across checkouts."""

import argparse
import os
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path
from time import perf_counter

ROOT = Path(__file__).resolve().parents[1]


def measure(checkout: Path) -> tuple[float, int]:
    with tempfile.TemporaryDirectory() as temporary:
        workspace = Path(temporary)
        shutil.copytree(ROOT / "tests/contract/devices", workspace, dirs_exist_ok=True)
        samples = []
        for _ in range(6):
            start = perf_counter()
            subprocess.run(
                [
                    sys.executable,
                    "-m",
                    "graphql_typed.cli",
                    "generate",
                    "schema.graphql",
                    "--out",
                    "generated",
                    "--operations",
                    "operations:operations",
                ],
                cwd=workspace,
                env={**os.environ, "PYTHONPATH": str(checkout.resolve())},
                check=True,
            )
            samples.append(perf_counter() - start)
            size = sum(p.stat().st_size for p in (workspace / "generated").glob("*.py"))
            shutil.rmtree(workspace / "generated")
        return min(samples[1:]), size


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--base", type=Path)
    args = parser.parse_args()
    seconds, size = measure(ROOT)
    print(f"Current: {seconds:.3f}s, {size:,} generated bytes")
    if args.base:
        previous_seconds, previous_size = measure(args.base)
        print(f"Base:    {previous_seconds:.3f}s, {previous_size:,} generated bytes")
        if seconds > previous_seconds * 1.02 or size > previous_size * 1.02:
            raise SystemExit(
                "Generation time or output size increased by more than 2%."
            )


if __name__ == "__main__":
    main()
